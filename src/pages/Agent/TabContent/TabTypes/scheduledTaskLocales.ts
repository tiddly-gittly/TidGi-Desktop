export function resolveScheduledTaskLocale(language: string): ResolvedScheduledTaskLocale {
  const normalized = language.toLowerCase();
  if (normalized.startsWith('zh-hant') || normalized.startsWith('zh-tw') || normalized.startsWith('zh-hk')) {
    return { cronLocale: 'en', customLocale: customLocales['zh-Hant'], dateLocale: 'zh-Hant' };
  }
  if (normalized.startsWith('zh')) return { cronLocale: 'zh_CN', dateLocale: 'zh-Hans' };
  if (normalized.startsWith('fr')) return { cronLocale: 'en', customLocale: customLocales.fr, dateLocale: 'fr' };
  if (normalized.startsWith('ja')) return { cronLocale: 'en', customLocale: customLocales.ja, dateLocale: 'ja' };
  if (normalized.startsWith('ru')) return { cronLocale: 'en', customLocale: customLocales.ru, dateLocale: 'ru' };
  return { cronLocale: 'en', dateLocale: 'en' };
}
